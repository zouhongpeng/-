/** 按方法名取卡的便捷缓存 */
const byId = new Map(METHOD_CARDS.map((c) => [c.id, c]));

/** 根据 theory_tag（卡片名）查找前端本地卡片，供分析结果里的依据讲解使用 */
export function findMethodByTitle(title?: string): MethodCard | undefined {
  if (!title) return undefined;
  return METHOD_CARDS.find((c) => title.includes(c.title) || c.title.includes(title));
}

export function findMethodById(id: string): MethodCard | undefined {
  return byId.get(id);
}