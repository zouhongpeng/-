/** 构建注入系统提示词的方法论区块（卡片全文，原样） */
export function buildMethodologySection(): string {
  const cards = METHODOLOGY_CARDS.map(
    (c, i) => `【卡${i + 1}·${c.title}】来源：${c.source}
适用场景：${c.scene}
${c.steps}
使用要点：${c.usage}
禁用提醒：${c.forbid}`
  ).join("\n\n");
  return cards;
}